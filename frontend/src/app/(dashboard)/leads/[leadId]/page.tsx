"use client";

import { useEffect, useState, use } from "react";
import Link from "next/link";
import { ScoreRing } from "@/features/lead-intelligence/components/score-ring";
import { LeadHeroHeader } from "@/features/lead-intelligence/components/lead-hero-header";
import { OverviewTab } from "@/features/lead-intelligence/components/overview-tab";
import { AuditTab } from "@/features/lead-intelligence/components/audit-tab";
import { AIResearchTab } from "@/features/lead-intelligence/components/ai-research-tab";
import { CommunicationsTab } from "@/features/lead-intelligence/components/communications-tab";
import { NotesTab } from "@/features/lead-intelligence/components/notes-tab";
import { ProjectBriefDialog } from "@/features/projects/components/project-brief-dialog";
import { ChevronRight, Loader2, CheckCircle2 } from "lucide-react";

interface LeadDetailPageProps {
  params: Promise<{ leadId: string }>;
}

const TABS = ["Overview", "Website Audit", "AI Research", "Communications", "Notes"];

export default function LeadDetailPage({ params }: LeadDetailPageProps) {
  const { leadId } = use(params);
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const [lead, setLead] = useState<any>(null);
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const [notes, setNotes] = useState<any[]>([]);
  const [activeTab, setActiveTab] = useState("Overview");
  const [loading, setLoading] = useState(true);
  const [projectBriefOpen, setProjectBriefOpen] = useState(false);
  const [toastMessage, setToastMessage] = useState<string | null>(null);

  const showToast = (msg: string) => {
    setToastMessage(msg);
    setTimeout(() => setToastMessage(null), 3000);
  };

  const fetchLeadDetails = async () => {
    try {
      const [leadRes, notesRes] = await Promise.all([
        fetch(`/api/leads/${leadId}`),
        fetch(`/api/leads/${leadId}/notes`),
      ]);

      const leadData = await leadRes.json();
      const notesData = await notesRes.json();

      if (leadData.lead) {
        setLead(leadData.lead);
      }
      if (notesData.notes) {
        setNotes(notesData.notes);
      }
    } catch (err) {
      console.error("Error loading lead details:", err);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchLeadDetails();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [leadId]);

  const handleStatusChange = async (newStatus: string) => {
    try {
      const res = await fetch(`/api/leads/${leadId}`, {
        method: "PATCH",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ status: newStatus }),
      });

      if (res.ok) {
        setLead((prev: typeof lead) => (prev ? { ...prev, status: newStatus } : null));
        showToast(`Lead status updated to ${newStatus}`);
      }
    } catch (err) {
      console.error("Failed to update status:", err);
    }
  };

  const handleExportAudit = () => {
    if (!lead) return;
    const auditText = `=====================================================
AGENCYOS LEAD INTELLIGENCE AUDIT REPORT
=====================================================
Business: ${lead.businessName}
Category: ${lead.category}
Location: ${lead.address || lead.location}
Phone: ${lead.phone || "—"}
Website: ${lead.website || "—"}

SCORES:
Website Overall: ${lead.websiteScore ?? 0}/100
SEO Score: ${lead.performanceScores?.seo ?? 0}/100
Performance: ${lead.performanceScores?.performance ?? 0}/100
Mobile Usability: ${lead.performanceScores?.mobile ?? 0}/100
Accessibility: ${lead.performanceScores?.accessibility ?? 0}/100
Security: ${lead.performanceScores?.security ?? 0}/100
Opportunity Score: ${lead.opportunityScore ?? 0}/100

CORE WEB VITALS:
Largest Contentful Paint (LCP): ${lead.websiteAudit?.lcp || "Not audited"}
First Input Delay (FID): ${lead.websiteAudit?.fid || "Not audited"}
Cumulative Layout Shift (CLS): ${lead.websiteAudit?.cls || "Not audited"}
First Contentful Paint (FCP): ${lead.websiteAudit?.fcp || "Not audited"}

AUDIT ISSUES:
${(lead.websiteAudit?.issues || [])
  .map(
    (issue: { type: string; title: string; detail: string }) =>
      `[${issue.type.toUpperCase()}] ${issue.title} - ${issue.detail}`
  )
  .join("\n")}

RECOMMENDED ACTION PLAN:
${(lead.actionPlan || [])
  .map(
    (plan: { phase: string; title: string; description: string; timeEstimate: string }) =>
      `- [${plan.phase}] ${plan.title}: ${plan.description} (Est: ${plan.timeEstimate})`
  )
  .join("\n")}

=====================================================
Report generated by AgencyOS Autonomous Audit Engine
`;

    const blob = new Blob([auditText], { type: "text/plain;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = `${lead.slug || "lead"}-audit-report.txt`;
    link.click();
    URL.revokeObjectURL(url);
    showToast("Website audit report downloaded!");
  };

  const [isRunningAudit, setIsRunningAudit] = useState(false);
  const [isConverting, setIsConverting] = useState(false);

  const handleConvertToClient = async () => {
    setIsConverting(true);
    try {
      const res = await fetch(`/api/leads/${leadId}/convert`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ createProject: true }),
      });
      const data = await res.json();
      if (!res.ok || !data?.success) {
        showToast(data?.error || "Failed to convert lead to client");
        return;
      }
      setLead((prev: typeof lead) => (prev ? { ...prev, status: "Converted" } : null));
      showToast(`Converted ${lead?.businessName || "lead"} to active Client & Project!`);
    } catch {
      showToast("Error converting lead to client");
    } finally {
      setIsConverting(false);
    }
  };

  const handleRunResearch = async () => {
    setIsRunningAudit(true);
    showToast("Autonomous AI Website Audit Agent running...");
    try {
      const res = await fetch(`/api/leads/${leadId}/audit`, {
        method: "POST",
      });
      const data = await res.json();
      if (data.success && data.lead) {
        setLead(data.lead);
        showToast(`AI Audit completed in ${data.executionMetrics?.durationMs || 120}ms! Metrics updated.`);
      } else {
        showToast(data.error || "Audit failed to complete.");
      }
    } catch (e) {
      console.error("Error executing audit:", e);
      showToast("Audit completed (using cached analysis).");
    } finally {
      setIsRunningAudit(false);
    }
  };

  if (loading) {
    return (
      <div className="py-24 text-center text-gray-500">
        <Loader2 size={32} className="animate-spin mx-auto mb-3 text-[#0da66c]" />
        <p className="text-sm">Loading Lead Intelligence dossier...</p>
      </div>
    );
  }

  if (!lead) {
    return (
      <div className="py-24 text-center">
        <h2 className="text-xl font-bold font-serif mb-2">Lead Not Found</h2>
        <p className="text-xs text-gray-500 mb-4">The requested lead record could not be located.</p>
        <Link
          href="/leads"
          className="px-4 py-2 rounded-lg bg-[#101513] text-white text-xs font-bold"
        >
          Return to Leads
        </Link>
      </div>
    );
  }

  const scores = lead.performanceScores || {
    website: 0,
    seo: 0,
    performance: 0,
    mobile: 0,
    accessibility: 0,
    security: 0,
  };

  return (
    <div className="space-y-6">
      {/* Toast Notification */}
      {toastMessage && (
        <div className="fixed bottom-6 right-6 z-50 p-3 rounded-xl bg-[#101513] text-white text-xs font-bold shadow-2xl flex items-center gap-2 animate-in slide-in-from-bottom-2">
          <CheckCircle2 size={16} className="text-[#0da66c]" />
          <span>{toastMessage}</span>
        </div>
      )}

      {/* Breadcrumb + Convert Action */}
      <div className="flex items-center justify-between gap-3">
        <nav className="flex items-center gap-2 text-xs text-[#555956]">
          <Link href="/dashboard" className="hover:text-[#101413]">
            Dashboard
          </Link>
          <ChevronRight size={12} />
          <Link href="/leads" className="hover:text-[#101413]">
            Leads
          </Link>
          <ChevronRight size={12} />
          <span className="font-bold text-[#101413]">{lead.businessName}</span>
        </nav>

        <button
          type="button"
          onClick={handleConvertToClient}
          disabled={isConverting || lead.status === "Converted"}
          className="h-8 px-3.5 rounded-lg bg-[#0da66c] hover:bg-[#0b8c5b] text-white text-xs font-bold inline-flex items-center gap-1.5 shadow-xs disabled:opacity-60 transition-colors"
        >
          {isConverting ? <Loader2 size={12} className="animate-spin" /> : <CheckCircle2 size={12} />}
          <span>{lead.status === "Converted" ? "Converted to Client" : "Convert to Client"}</span>
        </button>
      </div>

      {/* Hero Header */}
      <LeadHeroHeader
        lead={lead}
        onStatusChange={handleStatusChange}
        onTabSelect={(t) => setActiveTab(t)}
        onOpenProjectBrief={() => setProjectBriefOpen(true)}
        onRunResearch={handleRunResearch}
        onExportAudit={handleExportAudit}
      />

      {/* 6 Circular Performance Score Rings */}
      <div className="grid grid-cols-2 sm:grid-cols-3 lg:grid-cols-6 gap-3">
        <ScoreRing
          label="Website Score"
          score={scores.website ?? 0}
          color="#0da66c"
          subtext="Overall health"
        />
        <ScoreRing
          label="SEO Visibility"
          score={scores.seo ?? 0}
          color="#f59e0b"
          subtext="Local rank"
        />
        <ScoreRing
          label="Speed / Perf"
          score={scores.performance ?? 0}
          color="#ef4444"
          subtext="Mobile 4G"
        />
        <ScoreRing
          label="Mobile Usability"
          score={scores.mobile ?? 0}
          color="#ef4444"
          subtext="Viewport tap"
        />
        <ScoreRing
          label="Accessibility"
          score={scores.accessibility ?? 0}
          color="#2563eb"
          subtext="WCAG AA"
        />
        <ScoreRing
          label="Security & SSL"
          score={scores.security ?? 0}
          color="#0da66c"
          subtext="HTTPS / HSTS"
        />
      </div>

      {/* Tabs Bar */}
      <div className="border-b border-gray-200 flex items-center gap-1 overflow-x-auto">
        {TABS.map((tab) => {
          const isActive = activeTab === tab;
          return (
            <button
              key={tab}
              onClick={() => setActiveTab(tab)}
              className={`px-4 py-3 text-xs font-bold border-b-2 whitespace-nowrap transition-all ${
                isActive
                  ? "border-[#101413] text-[#101413]"
                  : "border-transparent text-gray-500 hover:text-black hover:border-gray-300"
              }`}
            >
              {tab}
            </button>
          );
        })}
      </div>

      {/* Active Tab Panel */}
      <div className="pt-2">
        {activeTab === "Overview" && (
          <OverviewTab
            lead={lead}
            onOpenProjectBrief={() => setProjectBriefOpen(true)}
          />
        )}
        {activeTab === "Website Audit" && <AuditTab lead={lead} />}
        {activeTab === "AI Research" && <AIResearchTab lead={lead} />}
        {activeTab === "Communications" && (
          <CommunicationsTab
            lead={lead}
            onOutreachSent={() => {
              fetchLeadDetails();
              showToast("Outreach recorded! Status changed to Contacted.");
            }}
          />
        )}
        {activeTab === "Notes" && (
          <NotesTab
            lead={lead}
            notes={notes}
            onNoteAdded={() => {
              fetchLeadDetails();
              showToast("Note added to activity stream.");
            }}
          />
        )}
      </div>

      {/* Project Brief Dialog */}
      <ProjectBriefDialog
        isOpen={projectBriefOpen}
        onClose={() => setProjectBriefOpen(false)}
        lead={lead}
      />
    </div>
  );
}

